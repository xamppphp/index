Задание PHP 19. Проверка натурального числа
=======================================================================

Что делает: проверяет, является ли число натуральным (целое и больше нуля).

Объяснение кода:
- fmod($a, 1) == 0 — проверяет, является ли число целым (остаток от 
  деления на 1 должен быть 0)
- $a > 0 — число больше нуля
- && — оба условия должны быть истинны

$a = 3;
if ($a > 0 && fmod($a, 1) == 0) {
    echo "Число натуральное";
} else {
    echo "Не натуральное";
}
// при a=3: "Число натуральное", при a=3.5: "Не натуральное"


