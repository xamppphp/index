1. Что такое PHP и как он работает?

PHP (Hypertext Preprocessor) — скриптовый язык программирования для веб-разработки. 
Код выполняется на стороне сервера, возвращает готовый HTML. Код встраивается через 
теги <?php ... ?>. Бесплатный, кроссплатформенный, поддерживает большинство серверов и БД.


2. Переменные в PHP: определение и правила именования

Переменная — именованный контейнер для хранения данных. Правила: начинается с $, 
имя из букв, цифр и _, не начинается с цифры, регистр важен. Тип определяется автоматически.
Пример: $age = 25; $name = "Анна";


3. Типы данных в PHP

- int (целые числа) — 1, 2, 100
- float (числа с плавающей точкой) — 1.5, 3.14
- string (строки) — "Привет", 'мир'
- bool (булев тип) — true/false
- array (массивы)
- object (объекты)
- NULL
- resource (ресурсы)


4. Условные операторы: if, else, elseif. Разветвляющиеся алгоритмы

Разветвляющийся алгоритм — выполнение разных блоков кода в зависимости от условия.

if (условие) { ... } else { ... } — два варианта.
elseif — добавляет дополнительные проверки.

Операторы сравнения: ==, !=, ===, !==, >, <, >=, <=
Логические: && (И), || (ИЛИ), ! (НЕ)

Тернарный оператор: условие ? значение1 : значение2


5. Оператор switch-case (множественный выбор)

Используется для сравнения одной переменной с несколькими значениями.

switch(переменная) {
    case значение1: код; break;
    case значение2: код; break;
    default: код по умолчанию;
}

break прерывает выполнение, default выполняется если ни один case не подошел.


6. Циклы в PHP: for, while, do-while, foreach. Разветвляющиеся циклы

Циклы — многократное выполнение кода.

- for — когда известно количество повторений: for($i=1; $i<=10; $i++) { ... }
- while — пока условие истинно: while($i<=10) { $i++; ... }
- do-while — сначала код, потом проверка (минимум 1 раз)
- foreach — для перебора массивов: foreach($arr as $value) или foreach($arr as $key=>$value)

Управление: break — досрочно прерывает, continue — пропускает итерацию.


7. Вложенные циклы и операторы break/continue

Вложенные циклы — один цикл внутри другого. Внешний выполняется медленнее, внутренний — быстрее.
Применяются для многомерных массивов, таблиц, матриц.

break — прерывает текущий цикл; break 2 — прерывает внешний цикл.
continue — пропускает итерацию; continue 2 — пропускает итерацию внешнего цикла.


8. Массивы в PHP: индексированные и ассоциативные

Массив — структура данных для хранения нескольких значений.

Индексированный (ключи — числа от 0): $colors = ["красный", "зеленый", "синий"]; 
Доступ: $colors[0]

Ассоциативный (ключи — строки): $user = ["name"=>"Анна", "age"=>25]; 
Доступ: $user["name"]

Многомерные массивы — массивы внутри массивов: $matrix = [[1,2],[3,4]];


9. Основные функции для работы с массивами

count($arr) — количество элементов
array_push($arr, $val) — добавить в конец
array_pop($arr) — удалить последний
array_shift($arr) — удалить первый
array_unshift($arr, $val) — добавить в начало
array_merge($arr1, $arr2) — объединить массивы
in_array($val, $arr) — проверить наличие значения
sort($arr) / rsort($arr) — сортировка по возрастанию/убыванию
asort($arr) / ksort($arr) — сортировка ассоциативного массива по значениям/ключам
print_r($arr) — вывод массива для отладки


10. Строки в PHP: определение и основные операции

Строка — последовательность символов. Создаются в одинарных или двойных кавычках.
Двойные кавычки обрабатывают переменные внутри (интерполяция).

Конкатенация — через точку: $str1 . $str2

Функции:
strlen($str) — длина
strpos($str, $search) — позиция вхождения
substr($str, start, length) — извлечение подстроки
str_replace("что", "на что", $str) — замена
strtolower($str) / strtoupper($str) — регистр
trim($str) — удаление пробелов
explode("разделитель", $str) — разбить в массив
implode("разделитель", $arr) — объединить массив в строку


11. Суперглобальные массивы ($_GET, $_POST, $_SERVER, $_SESSION)

Доступны в любой области видимости.

$_GET — данные из URL (метод GET). Видны в адресной строке.
$_POST — данные из тела запроса (метод POST). Не видны в URL.
$_SERVER — информация о сервере и окружении. $_SERVER['REQUEST_METHOD'] — метод запроса.
$_SESSION — данные сессии (требует session_start())
$_COOKIE — данные из куки-файлов
$_FILES — информация о загруженных файлах


12. Функции в PHP: определение, параметры, возврат значений

Функция — именованный блок кода для многократного вызова.

Определение: function имяФункции(параметры) { код; return значение; }

Параметры могут иметь значения по умолчанию: function greet($name = "Гость") { ... }
return — возвращает значение и прекращает выполнение функции.


13. Работа с базами данных в PHP (mysqli)

mysqli — расширение PHP для MySQL.

Подключение: mysqli_connect(сервер, пользователь, пароль, БД)
Запрос: mysqli_query($link, $sql)
Извлечение: mysqli_fetch_array($result) — массив с индексами и ключами
            mysqli_fetch_assoc($result) — только ассоциативный
            mysqli_fetch_row($result) — только индексированный
Количество строк: mysqli_num_rows($result)
Затронутые строки: mysqli_affected_rows($link)
ID последней вставки: mysqli_insert_id($link)
Ошибка: mysqli_error($link)
Закрытие: mysqli_close($link)


14. Основные SQL-запросы в PHP: SELECT, INSERT, UPDATE, DELETE

SELECT — выборка: "SELECT * FROM table WHERE условие"
INSERT — добавление: "INSERT INTO table (col1, col2) VALUES ('val1', val2)"
UPDATE — обновление: "UPDATE table SET col = value WHERE id = 1"
DELETE — удаление: "DELETE FROM table WHERE id = 1"

WHERE — условие фильтрации
ORDER BY — сортировка (ASC — по возрастанию, DESC — по убыванию)
LIMIT — ограничение количества записей


15. Обработка ошибок: try-catch и исключения

Исключения — механизм обработки ошибок.

try { код, где может быть ошибка }
catch (Exception $e) { обработка ошибки }
finally { выполняется всегда (необязательно) }

throw new Exception("сообщение") — выбрасывает исключение.
$e->getMessage() — получить сообщение об ошибке.


16. Разветвляющиеся алгоритмы: понятие и примеры в PHP

Разветвляющийся алгоритм — в зависимости от условия выполняется та или иная 
последовательность действий. Реализуется через if-else, if-elseif-else, switch-case, 
тернарный оператор. Могут быть вложенными. Используются внутри циклов для break/continue.


17. Итерационные алгоритмы (циклы): понятие и виды

Итерационный алгоритм — многократное выполнение действий (циклы).

Виды циклов в PHP:
- for — фиксированное число итераций
- while — повторение пока условие истинно
- do-while — гарантирует хотя бы одно выполнение
- foreach — для перебора массивов

Итерационные алгоритмы применяются для обработки массивов, перебора записей из БД, 
вывода таблиц и списков.


18. Рекурсия в PHP: понятие и применение

Рекурсия — вызов функцией самой себя. Обязательно должно быть условие выхода.
Применяется для обхода деревьев, вложенных массивов, вычисления факториала.

Пример факториала:
function factorial($n) {
    if ($n <= 1) return 1;
    else return $n * factorial($n - 1);
}

Недостаток: при глубокой рекурсии может переполниться стек вызовов.


19. Включение файлов: include, require, include_once, require_once

include — подключает файл, при ошибке — предупреждение (скрипт продолжает работу)
require — подключает файл, при ошибке — остановка скрипта
include_once / require_once — подключают файл только один раз

Применяются для подключения функций, классов, конфигурации, шаблонов.

