Задание PHP 18. try-catch деления на ноль
=======================================================================

Что делает: пытается разделить число на ноль и обрабатывает ошибку.

Объяснение кода:
- function divide($a, $b) — объявление функции с двумя параметрами
- throw new Exception("сообщение") — выбрасывает исключение
- try { ... } — блок, где может возникнуть ошибка
- catch (Exception $e) { ... } — перехватывает исключение
- $e->getMessage() — получает сообщение об ошибке

function divide($a, $b) {
    if ($b == 0) {
        throw new Exception("На ноль делить нельзя!");
    }
    return $a / $b;
}
try {
    echo divide(10, 0);
} catch (Exception $e) {
    echo "Ошибка: " . $e->getMessage();
}
// Результат: "Ошибка: На ноль делить нельзя!"


